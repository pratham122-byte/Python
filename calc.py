def add(x,y):
    return (x+y)
def subtract(x,y):
    return (x-y)
def mul(x,y):
    return (x*y)
def div(x,y):
    return (x/y)
def triangle(x,y):
    return (0.5*x*y)
def circle(x):
    return (2*3.14*x)
def larger(x,y):
    if x>y:
        return x
    else:
        return y
def possitive(x):
    if x>=0:
        return True
    else:
        return False   
def evenodd(x):
    if x%2==0:
        return "even"
    else:
        return "odd"